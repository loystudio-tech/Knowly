#!/bin/sh
# Netlify Edge Functions are bundled separately, so netlify/edge-functions/source.js is a
# self-contained copy of lib/source.js plus a small Netlify wrapper. Run this after editing lib/source.js.
set -e
cd "$(dirname "$0")/.."
{
  echo '// GENERATED by scripts/sync-netlify-source.sh from lib/source.js — edit lib/source.js, not this file.'
  cat lib/source.js
  cat <<'EOT'

/* ---------- Netlify wrapper ---------- */
const json = (obj, status) => new Response(JSON.stringify(obj), { status, headers: { 'content-type': 'application/json' } });

export default async (req) => {
  if (req.method !== 'POST') return json({ error: { message: 'Método no permitido' } }, 405);
  const password = Netlify.env.get('APP_PASSWORD');
  if (!password) return json({ error: { message: 'Falta APP_PASSWORD en las variables de entorno de Netlify.' } }, 500);
  if (req.headers.get('x-app-password') !== password) return json({ error: { message: 'Contraseña incorrecta' } }, 401);
  let body; try { body = await req.json(); } catch (e) { return json({ error: { message: 'Petición no válida' } }, 400); }
  return sourceResponse(body);
};

export const config = { path: '/api/source' };
EOT
} > netlify/edge-functions/source.js
